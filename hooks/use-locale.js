function getValue(dictionary, path) {
  return path.split('.').reduce((value, key) => value?.[key], dictionary);
}

function interpolate(value, variables) {
  return String(value).replace(/{{(.*?)}}/g, (_, key) => variables?.[key.trim()] ?? '');
}

export function LocaleProvider({ children }) {
  const [locale, setLocaleState] = useState('en');

  useEffect(() => {
    const storedLocale = window.localStorage.getItem(LOCALE_STORAGE_KEY);
    if (storedLocale && messages[storedLocale]) setLocaleState(storedLocale);
  }, []);

  useEffect(() => {
    window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
    document.documentElement.lang = locale;
  }, [locale]);

  useEffect(() => {
    function handleStorage(event) {
      if (event.key !== LOCALE_STORAGE_KEY) return;
      if (event.newValue && messages[event.newValue]) setLocaleState(event.newValue);
    }

    window.addEventListener('storage', handleStorage);
    return () => window.removeEventListener('storage', handleStorage);
  }, []);

  function setLocale(nextLocale) {
    if (messages[nextLocale]) setLocaleState(nextLocale);
  }

  const value = useMemo(() => ({
    locale,
    localeCode: locale === 'es' ? 'es-ES' : 'en-US',
    setLocale,
    t(path, variables) {
      const valueForLocale = getValue(messages[locale], path);
      const valueInEnglish = getValue(messages.en, path);
      return interpolate(valueForLocale ?? valueInEnglish ?? path, variables);
    },
    getCategoryLabel(category) {
      const name = typeof category === 'string' ? category : category?.name;
      return getValue(messages[locale], `categories.${name}`) || category?.label || name;
    },
  }), [locale]);

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export default function useLocale() {
  const context = useContext(LocaleContext);

  if (!context) throw new Error('useLocale must be used within LocaleProvider');

  return context;
}
